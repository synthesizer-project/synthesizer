"""A submodule for visualising emission model networks.

An EmissionModel describes a network of models connected by the operations
which turn one emission into another. This submodule draws that network, which
is the only practical way to understand a model of any size.

The whole network is drawn, not just the models reachable from a single root.
This matters because related models are roots in their own right, and expanding
a parameter variation attaches all but one of its variants as related models.

The drawing is a layered diagram, read bottom to top in the direction the
emission flows. It is built in the usual four stages:

1. Each model is placed on a row directly below the model which consumes it,
   so a grid extraction sits under whatever uses it. This keeps the diagram
   narrow; collecting every extraction onto a single bottom row instead makes
   the widest row as wide as the number of grids, which no amount of styling
   can rescue.
2. Rows are ordered by the barycentre of each model's neighbours to reduce edge
   crossings, with a placeholder standing in for each row an edge passes
   through. The placeholders reserve an empty column, so a long edge always has
   somewhere to run.
3. Columns are straightened, so chains of models line up rather than fanning.
4. Edges are routed as orthogonal elbows through the reserved columns, turning
   only in the gaps between rows. An edge therefore cannot cross a box.

Everything is measured and laid out in points, the units the boxes are drawn
in, so boxes cannot overlap regardless of the figure size. By default the
figure is sized to fit the network; if a figure size is given, the labels are
scaled down to fit it instead.

Passing layout="dot" hands the layering and placement to graphviz instead,
which is worth trying on dense networks. That needs pydot and the graphviz
binary.

Example usage::

    model.plot_emission_graph()
    model.plot_emission_graph(layout="dot")
    model.plot_emission_graph(show_variants=True)

Note that EmissionModel.plot_emission_graph is a thin wrapper around the
function of the same name here, so this module does not usually need to be
imported directly.
"""

